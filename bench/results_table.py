#!/usr/bin/env python3
"""Regenerate results/reference/TABLES.md from the dated logs.

The generator does not parse numbers. Every log in results/reference/ was
written by a different script with its own summary format, and a parser that
guessed at them would be one more place for a number to be silently wrong.
Instead it reproduces each log's summary block verbatim: the tail of the log
from the last blank line before its final result marker (a sign test, a
verification count, a coverage block). REFERENCE.md is transcribed by hand
from these blocks, and this file exists so that transcription can be checked
against the source in one place.

    python bench/results_table.py            # writes results/reference/TABLES.md
    python bench/results_table.py --check    # exit 1 if TABLES.md is stale
"""
import argparse
import datetime
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REF = ROOT / "results" / "reference"
OUT = REF / "TABLES.md"

# A line that ends a summary: a sign test, a verification tally, a verdict.
MARKER = re.compile(r"(p ?= ?0[.][0-9]+|verified|COVERAGE|-> |AHEAD|PARITY|not established|median)", re.I)
MAX_LINES = 60


def summary_block(lines):
    last = None
    for i, l in enumerate(lines):
        if MARKER.search(l):
            last = i
    if last is None:
        return lines[-30:]
    start = last
    while start > 0 and lines[start - 1].strip():
        start -= 1
    # widen to at least the whole final paragraph group, capped
    block = lines[start:]
    if len(block) > MAX_LINES:
        block = block[-MAX_LINES:]
    return block


def render():
    logs = sorted(p for p in REF.glob("*.log"))
    parts = ["# Reference logs: summary blocks",
             "",
             "Generated by `bench/results_table.py`; do not edit by hand. Each block is the",
             "verbatim tail of one log in this directory, from the last blank line before its",
             "final result marker. The tables in REFERENCE.md are transcribed from these.",
             "",
             "| log | lines | modified |",
             "|---|---|---|"]
    bodies = []
    for p in logs:
        text = p.read_text(encoding="utf-8", errors="replace")
        lines = text.splitlines()
        mtime = datetime.datetime.fromtimestamp(p.stat().st_mtime).date().isoformat()
        parts.append("| `%s` | %d | %s |" % (p.name, len(lines), mtime))
        block = summary_block(lines)
        bodies.append("## `%s`" % p.name)
        bodies.append("")
        bodies.append("```text")
        bodies.extend(l.rstrip() for l in block)
        bodies.append("```")
        bodies.append("")
    return chr(10).join(parts + [""] + bodies)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="exit 1 if TABLES.md differs from what would be generated")
    a = ap.parse_args()
    new = render()
    if a.check:
        old = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if old != new:
            print("TABLES.md is stale; run bench/results_table.py")
            return 1
        print("TABLES.md is current")
        return 0
    OUT.write_text(new, encoding="utf-8", newline=chr(10))
    n = len(list(REF.glob("*.log")))
    print("wrote %s from %d logs" % (OUT.relative_to(ROOT), n))
    return 0


if __name__ == "__main__":
    sys.exit(main())
